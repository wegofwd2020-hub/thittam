"""Render a validated company + vertical into ordered, idempotent seed SQL.

Output files (applied in name order with ``psql -v ON_ERROR_STOP=1``):

==================  ==========================================================
``001_tenant.sql``  ``tenants`` row, ``tenant_verticals`` binding, 7 system roles
``002_admin.sql``   first user + tenant-wide ``super_admin`` grant
``003_products.sql`` one ``productions`` row per product
``004_ledger.sql``  chart of accounts (from the vertical) + open periods
==================  ==========================================================

Every statement is safe to re-run: inserts use ``ON CONFLICT ... DO NOTHING``
and each file runs in a single transaction. The admin password hash is never
written into the files; it is supplied at apply time as the psql variable
``admin_password_hash`` and checked for bcrypt shape before use.
"""

